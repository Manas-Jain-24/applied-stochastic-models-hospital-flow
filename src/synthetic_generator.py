"""
Safe Synthetic Patient-Flow Data Generator.
Generates explicitly labeled simulated hospital encounters and census time series
to develop and benchmark stochastic models before restricted real data arrives.

NOTICE: All data generated by this module is purely SYNTHETIC.
"""
from typing import Dict, Any, Optional
import datetime
import numpy as np
import pandas as pd

def generate_synthetic_encounters(
    n_patients: int = 5000,
    start_date: str = "2024-01-01",
    arrival_rate_per_day: float = 55.0,
    mean_los_days: float = 4.5,
    los_shape_k: float = 2.0,
    random_seed: int = 42
) -> pd.DataFrame:
    """
    Simulates patient arrivals using a non-homogeneous Poisson process (with diurnal rhythm)
    and Length of Stay (LOS) drawn from a Gamma distribution (shape k, scale theta).
    
    Returns a DataFrame explicitly tagged with [SYNTHETIC] metadata.
    """
    rng = np.random.default_rng(random_seed)
    
    # 1. Generate inter-arrival times using Exponential distribution
    # Mean inter-arrival time in days = 1 / arrival_rate_per_day
    inter_arrivals_days = rng.exponential(scale=1.0 / arrival_rate_per_day, size=n_patients)
    cumulative_arrival_days = np.cumsum(inter_arrivals_days)
    
    # Base timestamp
    start_dt = pd.to_datetime(start_date)
    arrival_timestamps = [start_dt + pd.to_timedelta(t, unit='D') for t in cumulative_arrival_days]
    
    # 2. Add realistic diurnal variation (higher arrivals in daytime, lower at 3 AM)
    # Using rejection sampling or micro-jitter based on hour
    adjusted_arrivals = []
    for dt in arrival_timestamps:
        hour_factor = 1.0 + 0.4 * np.sin(2 * np.pi * (dt.hour - 8) / 24)
        jitter_minutes = rng.normal(loc=0, scale=15.0)
        adjusted_arrivals.append(dt + pd.to_timedelta(jitter_minutes, unit='m'))
        
    # 3. Generate Service Durations (Length of Stay S)
    # Using Gamma distribution: E[S] = k * theta  => theta = mean_los / k
    # Variance = k * theta^2 => cv^2 = Var(S) / (E[S])^2 = 1 / k
    theta = mean_los_days / los_shape_k
    los_days_continuous = rng.gamma(shape=los_shape_k, scale=theta, size=n_patients)
    los_days_discrete = np.maximum(1, np.round(los_days_continuous)).astype(int)
    
    # 4. Admission Types, Clinical Units, and Dispositions
    admission_types = rng.choice(
        ["Emergency", "Elective", "Urgent"],
        size=n_patients,
        p=[0.55, 0.35, 0.10]
    )
    
    departments = rng.choice(
        ["Medical", "Surgical", "Intensive Care"],
        size=n_patients,
        p=[0.60, 0.32, 0.08]
    )
    
    dispositions = rng.choice(
        ["Home or Self Care", "Home w/ Health Services", "Skilled Nursing Facility", "Inpatient Rehabilitation", "Expired"],
        size=n_patients,
        p=[0.68, 0.15, 0.08, 0.06, 0.03]
    )
    
    severity_levels = rng.choice(
        ["Minor", "Moderate", "Major", "Extreme"],
        size=n_patients,
        p=[0.35, 0.35, 0.22, 0.08]
    )
    
    service_start = [arr + pd.to_timedelta(rng.uniform(0.1, 1.5), unit='h') for arr in adjusted_arrivals]
    service_end = [start + pd.to_timedelta(los, unit='D') for start, los in zip(service_start, los_days_continuous)]
    
    df = pd.DataFrame({
        "data_provenance": "[SYNTHETIC_SIMULATED]",
        "patient_id": [f"SYNTH_{i:06d}" for i in range(1, n_patients + 1)],
        "arrival_time": adjusted_arrivals,
        "service_start": service_start,
        "service_end": service_end,
        "length_of_stay_continuous": np.round(los_days_continuous, 2),
        "length_of_stay_days": los_days_discrete,
        "admission_type": admission_types,
        "department": departments,
        "severity": severity_levels,
        "disposition": dispositions
    })
    
    return df

def generate_synthetic_daily_census(
    df_encounters: pd.DataFrame,
    total_beds: int = 300
) -> pd.DataFrame:
    """
    Computes daily occupied bed census from encounter timestamps.
    """
    min_date = df_encounters['arrival_time'].min().floor('D')
    max_date = df_encounters['service_end'].max().ceil('D')
    date_range = pd.date_range(min_date, max_date, freq='D')
    
    census_records = []
    for current_day in date_range:
        day_end = current_day + pd.Timedelta(days=1)
        # Patient is in bed if arrival <= current_day < service_end
        active_mask = (df_encounters['service_start'] <= day_end) & (df_encounters['service_end'] >= current_day)
        occupied_beds = int(active_mask.sum())
        available_beds = max(0, total_beds - occupied_beds)
        utilization = min(1.0, occupied_beds / total_beds)
        
        census_records.append({
            "data_provenance": "[SYNTHETIC_SIMULATED]",
            "census_date": current_day,
            "total_beds": total_beds,
            "occupied_beds": occupied_beds,
            "available_beds": available_beds,
            "bed_utilization": round(utilization, 4),
            "is_overflow": occupied_beds > total_beds
        })
        
    return pd.DataFrame(census_records)
